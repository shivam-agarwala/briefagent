"""
Turn the validated claims structure into brief.md.

The model never writes markdown itself. It returns structured claims and this
file renders them. That means the eval can read claims as data instead of
regex-parsing prose, and every brief has identical shape across systems.
"""

from __future__ import annotations

SECTIONS = [
    ("what_they_sell", "What they sell"),
    ("who_they_sell_to", "Who they sell to"),
    ("outreach_hook", "Outreach hook"),
]


def render_brief(brief: dict) -> str:
    name = brief.get("company_name") or brief.get("company_url", "Unknown company")
    lines = ["# %s" % name, ""]
    lines.append("Source: %s" % brief.get("company_url", ""))
    lines.append("")

    if brief.get("incomplete"):
        lines.append(
            "> Draft is incomplete. The run stopped early (%s), so this brief "
            "is based on fewer pages than planned."
            % brief.get("incomplete_reason", "limit reached")
        )
        lines.append("")

    for key, heading in SECTIONS:
        lines.append("## %s" % heading)
        lines.append("")
        claims = brief.get(key) or []
        if not claims:
            lines.append("_No supported claim found._")
            lines.append("")
            continue
        for claim in claims:
            lines.append(
                "- %s ([source](%s))" % (claim["claim"].rstrip(), claim["source_url"])
            )
        lines.append("")

    dropped = brief.get("dropped_claims") or []
    if dropped:
        lines.append("## Dropped claims")
        lines.append("")
        lines.append(
            "These were produced by the model but cited a page the agent never "
            "successfully fetched, so they were removed."
        )
        lines.append("")
        for claim in dropped:
            lines.append("- %s (claimed source: %s)" % (claim["claim"], claim["source_url"]))
        lines.append("")

    lines.append("---")
    lines.append("")
    lines.append("Generated by briefagent. Draft only, nothing was sent anywhere.")
    lines.append("")
    return "\n".join(lines)
